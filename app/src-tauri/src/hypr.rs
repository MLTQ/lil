//! Hyprland support: one query for cursor, window and grab key; moving the window; the rule to ship. See hypr.md.
//! A Wayland client cannot read the global cursor or keys, place itself or stay on top; the compositor has to help.
use crate::config::Config;
use crate::cursor::Sample;
use std::{env, io::{Read, Write}, os::unix::net::UnixStream, path::PathBuf};

/// True when running inside a Hyprland session.
pub fn active() -> bool { env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some() }

/// One request on Hyprland's command socket (the one hyprctl uses). `j/` asks for JSON, `repl` runs Lua.
fn request(cmd: &str) -> Option<String> {
    let path = PathBuf::from(env::var_os("XDG_RUNTIME_DIR")?)
        .join("hypr").join(env::var_os("HYPRLAND_INSTANCE_SIGNATURE")?).join(".socket.sock");
    let mut s = UnixStream::connect(path).ok()?;
    s.write_all(cmd.as_bytes()).ok()?;
    let mut out = String::new();
    s.read_to_string(&mut out).ok()?;
    Some(out)
}

fn keysyms(grab: &str) -> Option<(&'static str, &'static str)> {
    Some(match grab {
        "alt" => ("Alt_L", "Alt_R"),
        "ctrl" => ("Control_L", "Control_R"),
        "shift" => ("Shift_L", "Shift_R"),
        "super" => ("Super_L", "Super_R"),
        _ => return None,
    })
}

/// Cursor, this process's window and the grab key, in one round trip (about 7 ms through hyprctl, less here).
/// Returns None until the window is mapped.
pub fn sample(grab: &str) -> Option<Sample> {
    let key = match keysyms(grab) {
        Some((l, r)) => format!(r#"tostring(hl.is_key_down("{l}") or hl.is_key_down("{r}"))"#),
        None => r#""false""#.to_string(),
    };
    let lua = format!(
        r#"repl local c=hl.get_cursor_pos() local w=hl.get_window("pid:{pid}") if not w then return "" end return c.x.." "..c.y.." "..w.at.x.." "..w.at.y.." "..w.size.x.." "..w.size.y.." "..{key}"#,
        pid = std::process::id()
    );
    let out = request(&lua)?;
    let mut f = out.split_whitespace();
    let mut n = || f.next()?.parse::<f64>().ok();
    let (cursor, at, size) = ((n()?, n()?), (n()?, n()?), (n()?, n()?));
    Some(Sample { cursor, at, size, grab: f.next() == Some("true") })
}

/// Moves this process's window so its top-left corner is at (x, y) in layout coordinates.
pub fn move_to(x: f64, y: f64) {
    request(&format!(
        r#"repl hl.dispatch(hl.dsp.window.move({{ x = {}, y = {}, window = "pid:{}" }}))"#,
        x.round(), y.round(), std::process::id()
    ));
}

/// Initial placement: the saved position, else the configured corner of the focused monitor inside its reserved
/// area (the bar). Call once the window is mapped.
pub fn place(cfg: &Config) -> Option<()> {
    if let Some([x, y]) = cfg.window.position { move_to(x, y); return Some(()); }
    let v: serde_json::Value = serde_json::from_str(&request("j/monitors")?).ok()?;
    let mons = v.as_array()?;
    let m = mons.iter().find(|m| m["focused"].as_bool() == Some(true)).or(mons.first())?;
    let k = m["scale"].as_f64()?;
    let (x0, y0, w, h) = (m["x"].as_f64()?, m["y"].as_f64()?, m["width"].as_f64()? / k, m["height"].as_f64()? / k);
    let r: Vec<f64> = m["reserved"].as_array()?.iter().filter_map(|n| n.as_f64()).collect(); // left, top, right, bottom
    let (size, mg) = (cfg.render.res as f64 * cfg.window.scale, cfg.window.margin);
    let x = if cfg.window.corner.ends_with("left") { x0 + r.first()? + mg } else { x0 + w - r.get(2)? - size - mg };
    let y = if cfg.window.corner.starts_with("top") { y0 + r.get(1)? + mg } else { y0 + h - r.get(3)? - size - mg };
    move_to(x, y);
    Some(())
}

/// The Lua window rule for this instance, for Hyprland's Lua config (0.56 on Omarchy). Printed by
/// `lil --print-hyprland-rules`. Matches on class plus the instance name, so two creatures get two rules.
/// It has no `move`: the app places itself over the socket, so a dragged position survives a restart.
pub fn rules(cfg: &Config) -> String {
    format!(
        r#"-- lil creature "{name}": floats on every workspace, takes no focus, has no decoration.
-- Generated by `lil --print-hyprland-rules`. Regenerate if the instance name in lil.config.json changes.
hl.window_rule({{
  match = {{ class = "^lil$", title = "^{name}$" }},
  float = true,
  pin = true,
  no_focus = true,
  border_size = 0,
  rounding = 0,
  no_blur = true,
  no_shadow = true,
  no_anim = true,
  no_dim = true,
}})
"#,
        name = cfg.name
    )
}
